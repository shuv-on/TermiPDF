"""
make_demo_pdf.py — Build a 5-page demo PDF for screenshot capture.

Produces ``docs/screenshots/_assets/demo.pdf`` with content designed to be
visible in feature screenshots:

  Page 1 — Title page (large heading, subtitle, footer)
  Page 2 — Body text (3 paragraphs + a styled section header)
  Page 3 — Embedded image (an 800x500 PNG rendered into the page)
  Page 4 — Multi-page TOC mock (so the outline sidebar isn't empty)
  Page 5 — Wide-aspect table (so ``rotate`` produces a visible change)

Run from the project root:
    source .venv/bin/activate
    python tests/make_demo_pdf.py

The script is idempotent: rerun any time to refresh the fixture.
"""
from __future__ import annotations

import io
import json
import sys
from pathlib import Path

import fitz  # PyMuPDF
from PIL import Image as PILImage

PROJECT_ROOT = Path(__file__).resolve().parents[1]
ASSET_DIR = PROJECT_ROOT / "docs" / "screenshots" / "_assets"
OUT_PDF = ASSET_DIR / "demo.pdf"
MANIFEST = ASSET_DIR / "manifest.json"

# Use Helvetica core fonts so the script doesn't depend on
# any external TTF (these are always available in PyMuPDF).
FONT_REG = "helv"
FONT_BOLD = "hebo"
FONT_OBL = "heit"


